#!/usr/bin/env node
// Pre-generates the Slingshot campaign so every browser gets identical, instantly-loaded levels.
//   node games/slingshot/tools/build-campaign.cjs
// Each level is re-verified (a winning shot exists that collects all three shards) before it is written.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = { window: {}, console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'js/world.js'), 'utf8'), ctx);
const SL = ctx.window.Slingshot;

const levels = [];
for (let ch = 0; ch < SL.CHAPTERS.length; ch++) {
	for (let li = 0; li < SL.LEVELS_PER_CHAPTER; li++) {
		const L = SL.campaignLevel(ch, li);
		const r = SL.simulate(L, L.solution.angle, L.solution.speed);
		if (r.outcome !== 'target' || r.shards.length !== 3) throw new Error(`level ${ch}:${li} failed verification`);
		const { solution, seed, wins, w, h, ...data } = L;
		levels.push(data);
		process.stdout.write(`${ch}:${li} `);
	}
}
const out = `/* Generated by tools/build-campaign.cjs — do not edit by hand. */\nwindow.Slingshot = window.Slingshot || {};\nwindow.Slingshot.CAMPAIGN = ${JSON.stringify(levels)};\n`;
fs.writeFileSync(path.join(root, 'js/campaign.js'), out);
console.log(`\nWrote ${levels.length} levels (${(out.length / 1024).toFixed(1)} KB).`);
